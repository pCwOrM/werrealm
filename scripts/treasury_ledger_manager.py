    for evt in b.get("burn_events", []):
        md += f"| `{evt['event_id']}` | {evt['timestamp_utc']}<br/>Block {evt['block_number']:,} | {evt['product_platform']}<br/>`{evt['invoice_no']}` | **{evt['werr_burned']:,.0f} WERR** | [Verify Tx ({evt['tx_hash'][:10]}...) ↗]({evt['explorer_url']}) |\n"

